#!/usr/bin/env node
// Regenerates per-page ai-audit-docs/INDEX.md tables and docs/ai-audit/timeline.md + INDEX.md
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '../../..');
const configPath = path.join(root, 'apps/delivery-ops/server/config/aiAudit.config.json');

function loadConfig() {
  return JSON.parse(fs.readFileSync(configPath, 'utf8'));
}

function parseFrontmatter(content) {
  if (!content.startsWith('---')) return {};
  const end = content.indexOf('\n---', 3);
  if (end === -1) return {};
  const yaml = content.slice(4, end);
  const fm = {};
  for (const line of yaml.split('\n')) {
    const m = line.match(/^\s*(\w+):\s*(.*)\s*$/);
    if (m) fm[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return fm;
}

function extractTitle(content) {
  const m = content.match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : '';
}

function collectEntries(auditAbsPath) {
  if (!fs.existsSync(auditAbsPath)) return [];
  const files = fs.readdirSync(auditAbsPath)
    .filter(f => f.endsWith('.md') && f !== 'INDEX.md')
    .sort(); // YYYY-MM-DD prefix sorts chronologically
  return files.map(f => {
    const full = path.join(auditAbsPath, f);
    const content = fs.readFileSync(full, 'utf8');
    const fm = parseFrontmatter(content);
    return { file: f, fm, title: extractTitle(content), full };
  });
}

function buildPerPageIndex(pageName, page, entries) {
  const lines = [];
  lines.push(`# ${page.title || pageName} — AI Audit Trail`);
  lines.push('');
  lines.push(`> Source: \`${page.source}\` | Route: \`${page.route}\` | Registry: \`apps/delivery-ops/server/config/aiAudit.config.json#pages.${pageName}\``);
  lines.push('');
  if (entries.length === 0) {
    lines.push('_No entries yet._');
  } else {
    lines.push('| Date | File | Weave | Goal |');
    lines.push('|------|------|-------|------|');
    for (const e of entries) {
      const date = e.fm.date || e.file.slice(0, 10);
      const weave = e.fm.weave || '';
      const goal = (e.fm.goal || '').replace(/\|/g, '\\|');
      lines.push(`| ${date} | [${e.file}](./${e.file}) | \`${weave}\` | ${goal} |`);
    }
  }
  lines.push('');
  lines.push(`_Generated by \`scripts/loom/ai-audit/rebuild-indexes.js\` — do not hand-edit table rows._`);
  lines.push('');
  return lines.join('\n');
}

function rebuildOne(pageName, config) {
  const page = config.pages[pageName];
  if (!page) { console.error(`Unknown page: ${pageName}`); process.exit(1); }
  const auditPath = path.join(root, page.auditPath);
  const entries = collectEntries(auditPath);
  const index = buildPerPageIndex(pageName, page, entries);
  if (!fs.existsSync(auditPath)) fs.mkdirSync(auditPath, { recursive: true });
  fs.writeFileSync(path.join(auditPath, 'INDEX.md'), index);
  console.log(`INDEX: ${page.auditPath}/INDEX.md (${entries.length} entries)`);
  return entries.map(e => ({ ...e, pageName, page }));
}

function rebuildAll() {
  const config = loadConfig();
  const filter = process.argv.includes('--page') ? process.argv[process.argv.indexOf('--page') + 1] : null;
  let allEntries = [];
  const pages = filter ? [filter] : Object.keys(config.pages);
  for (const p of pages) {
    const entries = rebuildOne(p, config);
    allEntries = allEntries.concat(entries);
  }
  if (!filter) {
    // Build cross-page timeline + hub
    allEntries.sort((a, b) => a.file.localeCompare(b.file));
    buildTimeline(allEntries, config);
    buildHub(config);
  }
}

function buildTimeline(allEntries, config) {
  const outDir = path.join(root, 'docs/ai-audit');
  fs.mkdirSync(outDir, { recursive: true });
  const lines = [];
  lines.push('# AI Audit Timeline — All Pages');
  lines.push('');
  lines.push('> Chronological across every page. Each row links to that page\'s journal entry.');
  lines.push('');
  if (allEntries.length === 0) {
    lines.push('_No entries yet._');
  } else {
    lines.push('| Date | Page | File | Weave | Goal |');
    lines.push('|------|------|------|-------|------|');
    for (const e of allEntries) {
      const date = e.fm.date || e.file.slice(0, 10);
      const weave = e.fm.weave || '';
      const goal = (e.fm.goal || '').replace(/\|/g, '\\|');
      const rel = path.relative(path.join(root, 'docs/ai-audit'), path.join(root, e.page.auditPath, e.file));
      lines.push(`| ${date} | ${e.pageName} | [${e.file}](${rel}) | \`${weave}\` | ${goal} |`);
    }
  }
  lines.push('');
  lines.push('_Generated by `scripts/loom/ai-audit/rebuild-indexes.js`._');
  fs.writeFileSync(path.join(outDir, 'timeline.md'), lines.join('\n'));
  console.log(`TIMELINE: docs/ai-audit/timeline.md (${allEntries.length} entries)`);
}

function buildHub(config) {
  const outDir = path.join(root, 'docs/ai-audit');
  fs.mkdirSync(outDir, { recursive: true });
  const hubPath = path.join(outDir, 'INDEX.md');
  // Don't overwrite hub if it already has substantial hand-written content beyond the table — regenerate the table section only
  // For now, fully generate it; hand-written intro lives in README.md
  const lines = [];
  lines.push('# AI Audit — Hub');
  lines.push('');
  lines.push('Per-page chronological AI audit trails. See [`LEARNINGS.md`](./LEARNINGS.md) for cross-page mistakes that must not repeat.');
  lines.push('');
  lines.push('| Page | Route | Audit Path |');
  lines.push('|------|-------|------------|');
  for (const [name, page] of Object.entries(config.pages)) {
    const auditRel = path.relative(path.join(root, 'docs/ai-audit'), path.join(root, page.auditPath));
    lines.push(`| ${name} | \`${page.route}\` | [\`${page.auditPath}\`](../../${page.auditPath}/) · [INDEX](../../${page.auditPath}/INDEX.md) |`);
  }
  lines.push('');
  lines.push(`- Timeline: [timeline.md](./timeline.md) — all pages chronological`);
  lines.push(`- Learnings: [LEARNINGS.md](./LEARNINGS.md) — anti-repeat log`);
  lines.push(`- Registry: [\`aiAudit.config.json\`](../../apps/delivery-ops/server/config/aiAudit.config.json)`);
  lines.push('');
  lines.push('_Generated by `scripts/loom/ai-audit/rebuild-indexes.js`._');
  fs.writeFileSync(hubPath, lines.join('\n'));
  console.log(`HUB: docs/ai-audit/INDEX.md`);
}

rebuildAll();
